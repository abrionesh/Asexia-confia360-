export const generateAiResponseDraft = (
  review: PublicReview,
  tone: 'empatico' | 'protocolario' | 'agradecimiento' = 'empatico'
): string => {
  const author = review.autor || 'estimado cliente';
  if (review.puntuacion >= 4) {
    if (tone === 'agradecimiento') {
      return `¡Muchísimas gracias por tu excelente valoración, ${author}! Nos alegra inmensamente que disfrutaras de tu experiencia con nosotros${
        review.platoMencionado ? ` y en especial de nuestro ${review.platoMencionado}` : ''
      }. Todo el equipo de cocina y sala trabaja con pasión para que cada visita sea memorable. ¡Esperamos darte la bienvenida muy pronto de nuevo!`;
    }
    return `Muchas gracias por compartir tu reseña, ${author}. Saber que has tenido una estancia tan agradable y que valoras nuestro servicio nos motiva a seguir superándonos cada día. ¡Será un auténtico placer recibirte pronto!`;
  } else if (review.puntuacion === 3) {
    return `Hola ${author}, te agradecemos el tiempo dedicado a valorarnos. Nos alegra ver aspectos positivos, pero tomamos muy en cuenta tus observaciones sobre ${
      review.motivos.join(', ') || 'el servicio'
    } para seguir puliendo la experiencia de sala y cocina. Nos gustaría volver a verte para ofrecerte una velada de 5 estrellas.`;
  } else {
    return `Estimado/a ${author}, lamentamos sinceramente que tu visita no haya estado a la altura de lo que esperamos ofrecer. La calidad del producto y la agilidad de los tiempos son prioritarias para nosotros. Hemos trasladado tus comentarios al Jefe de Cocina y al Maître para corregirlo de inmediato. Nos gustaría que nos contactes directamente para resarcir este desajuste y demostrarte nuestro estándar real.`;
  }
};
